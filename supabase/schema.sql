-- ---------------------------------------------------------------------------
-- 2) USUARIOS
--    password_hash = sha256(salt || password) en hex, guardado como "salt$hash"
--    modulos: array de módulos permitidos
--      inicio | servicio | ordenes | ventas | stock | caja
--      | presupuestos | clientes | facturacion | usuarios
-- ---------------------------------------------------------------------------
create table if not exists public.usuarios (
  id           bigint generated by default as identity primary key,
  usuario      text        not null unique,
  nombre       text        not null default '',
  password_hash text       not null,
  rol          text        not null default 'usuario' check (rol in ('admin','usuario')),
  sucursal_id  bigint      references public.sucursales(id) on delete restrict,
  modulos      text[]      not null default '{}',
  activo       boolean     not null default true,
  created_at   timestamptz not null default now()
);

