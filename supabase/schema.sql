-- ---------------------------------------------------------------------------
-- 3) CIERRES DE CAJA (apertura + cierre, por usuario y sucursal)
-- ---------------------------------------------------------------------------
create table if not exists public.cierres_caja (
  id                bigint generated by default as identity primary key,
  usuario_id        bigint      references public.usuarios(id) on delete set null,
  sucursal_id       bigint      references public.sucursales(id) on delete restrict,
  turno             text        not null default '',          -- texto libre (Mañana, Tarde, ...)
  monto_inicial     numeric(14,2) not null default 0,
  fecha_apertura    timestamptz not null default now(),
  fecha_cierre      timestamptz,
  monto_contado     numeric(14,2),                            -- efectivo contado al cerrar
  total_ventas      numeric(14,2) not null default 0,
  total_efectivo    numeric(14,2) not null default 0,
  total_transferencia numeric(14,2) not null default 0,
  total_tarjeta     numeric(14,2) not null default 0,
  diferencia        numeric(14,2),                            -- contado - esperado
  estado            text        not null default 'abierto' check (estado in ('abierto','cerrado')),
  notas             text        default '',
  created_at        timestamptz not null default now()
);

create index if not exists idx_cierres_sucursal  on public.cierres_caja (sucursal_id);
create index if not exists idx_cierres_usuario   on public.cierres_caja (usuario_id);
-- a lo sumo UNA caja abierta por usuario
create unique index if not exists uq_cierres_abierto
  on public.cierres_caja (usuario_id) where estado = 'abierto';

-- ---------------------------------------------------------------------------
-- 4) MOVIMIENTOS DE CAJA
--    Lo que se vende del stock, los servicios técnicos cobrados y las señas.
-- ---------------------------------------------------------------------------
create table if not exists public.movimientos_caja (
  id            bigint generated by default as identity primary key,
  cierre_id     bigint      references public.cierres_caja(id) on delete cascade,
  sucursal_id   bigint,
  usuario_id    bigint,
  turno         text        default '',   -- copiado del cierre (quedó en el historial)
  tipo          text        not null default 'producto'
                          check (tipo in ('producto','servicio_tecnico','seña','ajuste')),
  referencia_id bigint,                   -- id de la venta u orden asociada
  concepto      text        default '',
  metodo_pago   text        default 'Efectivo',
  monto         numeric(14,2) not null default 0,
  estado        text        not null default 'completada' check (estado in ('completada','cancelada')),
  created_at    timestamptz not null default now()
);

create index if not exists idx_mov_cierre   on public.movimientos_caja (cierre_id);
create index if not exists idx_mov_sucursal on public.movimientos_caja (sucursal_id);
create index if not exists idx_mov_usuario  on public.movimientos_caja (usuario_id);
create index if not exists idx_mov_fecha    on public.movimientos_caja (created_at);

-- ---------------------------------------------------------------------------
-- 5) COLUMNAS NUEVAS EN TABLAS EXISTENTES
-- ---------------------------------------------------------------------------
alter table public.stock       add column if not exists sucursal_id bigint;
alter table public.ordenes     add column if not exists sucursal_id bigint;
alter table public.presupuestos add column if not exists sucursal_id bigint;

alter table public.ventas add column if not exists sucursal_id bigint;
alter table public.ventas add column if not exists usuario_id  bigint;
alter table public.ventas add column if not exists cierre_id   bigint;
alter table public.ventas add column if not exists tipo        text not null default 'producto';
alter table public.ventas add column if not exists fecha_iso   timestamptz;

create index if not exists idx_stock_sucursal   on public.stock    (sucursal_id);
create index if not exists idx_ordenes_sucursal on public.ordenes  (sucursal_id);
create index if not exists idx_ventas_sucursal  on public.ventas   (sucursal_id);
create index if not exists idx_ventas_cierre    on public.ventas   (cierre_id);
create index if not exists idx_ventas_usuario   on public.ventas   (usuario_id);

-- ---------------------------------------------------------------------------
-- 6) BACKFILL: todo lo que ya existe pasa a la sucursal principal
-- ---------------------------------------------------------------------------
with principal as (select id from public.sucursales where es_principal = true limit 1)
update public.stock        set sucursal_id = (select id from principal) where sucursal_id is null;

with principal as (select id from public.sucursales where es_principal = true limit 1)
update public.ordenes      set sucursal_id = (select id from principal) where sucursal_id is null;

with principal as (select id from public.sucursales where es_principal = true limit 1)
update public.presupuestos set sucursal_id = (select id from principal) where sucursal_id is null;

with principal as (select id from public.sucursales where es_principal = true limit 1)
update public.ventas       set sucursal_id = (select id from principal) where sucursal_id is null;

